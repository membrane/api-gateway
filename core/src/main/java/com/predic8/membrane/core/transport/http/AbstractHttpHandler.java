package com.predic8.membrane.core.transport.http;

import com.predic8.membrane.core.exchange.Exchange;
import com.predic8.membrane.core.http.ReadingBodyException;
import com.predic8.membrane.core.http.Request;
import com.predic8.membrane.core.http.Response;
import com.predic8.membrane.core.http.WritingBodyException;
import com.predic8.membrane.core.transport.Transport;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.io.IOException;
import java.net.InetAddress;

import static com.predic8.membrane.core.exceptions.ProblemDetails.internal;
import static com.predic8.membrane.core.util.ExceptionUtil.concatMessageAndCauseMessages;
import static com.predic8.membrane.core.util.ExceptionUtil.isPeerDisconnect;

public abstract class AbstractHttpHandler  {

	private static final Logger log = LoggerFactory.getLogger(AbstractHttpHandler.class.getName());

	protected Exchange exchange;
	protected Request srcReq;
	private final Transport transport;

	public AbstractHttpHandler(Transport transport) {
		this.transport = transport;
	}

	public Transport getTransport() {
		return transport;
	}

	/**
	 * Only use for HTTP/1.0 requests. (see {@link HttpClient})
	 */
	public abstract void shutdownInput() throws IOException;
	public abstract InetAddress getLocalAddress();
	public abstract int getLocalPort();

	protected void invokeHandlers() throws AbortException, NoMoreRequestsException, EOFWhileReadingFirstLineException {
		try {
			getTransport().getRouter().getFlowController().invokeRequestHandlers(exchange, transport.getFlow());
			if (exchange.getResponse() == null) {
				log.error("Interceptor chain returned no response (path={}, flow={})", exchange.getRequest().getUri(), transport.getFlow());
				internal(transport.getRouter().getConfiguration().isProduction(),"http-handler")
						.addSubSee("no-response-produced")
						.detail("No response was generated by the interceptor chain.")
						.internal("interceptors", transport.getFlow())
						.buildAndSetResponse(exchange);
			}
		} catch (Exception e) {
			if (exchange.getResponse() == null)
				exchange.setResponse(generateErrorResponse(e));

			// TODO What is going on here?
            switch (e) {
                case AbortException abortException -> throw abortException;
                case NoMoreRequestsException noMoreRequestsException -> throw noMoreRequestsException;
                case NoResponseException noResponseException -> throw noResponseException;
                case EOFWhileReadingFirstLineException eofWhileReadingFirstLineException ->
                        throw eofWhileReadingFirstLineException;
                default -> {
                }
            }
            log.warn("An exception occurred while handling a request: ", e);
		}
	}

	/**
	 * Reading a body can fail on either end: the client while its request body is being read, or the
	 * target server while its response body is being streamed to the client. Attribute the failure to
	 * the body that actually recorded it, and log a peer going away as normal operation rather than as
	 * an error.
	 */
	protected void logReadingBodyException(ReadingBodyException e) {
		if (!isPeerDisconnect(e)) {
			log.error("", e);
			return;
		}
		if (e.belongsTo(exchange.getResponse()))
			log.warn("Server connection to {} closed while the response body was being read: {}",
					exchange.getDestinations(), concatMessageAndCauseMessages(e));
		else if (e.belongsTo(exchange.getRequest()))
			log.info("Client closed the connection while its request body was being read: {}",
					concatMessageAndCauseMessages(e));
		else
			log.info("Connection closed while a message body was being read: {}",
					concatMessageAndCauseMessages(e));
	}

	/**
	 * Only writing the response to the client can reach the handlers: a failure writing the request body
	 * to the target is swallowed by {@link #invokeHandlers()} and turned into a 500. So this is always
	 * the client's end.
	 */
	protected void logWritingBodyException(WritingBodyException e) {
		if (isPeerDisconnect(e))
			log.info("Client closed the connection while the response body was being written: {}",
					concatMessageAndCauseMessages(e));
		else
			log.error("", e);
	}

	private Response generateErrorResponse(Exception e) {
		return internal(transport.getRouter().getConfiguration().isProduction(),"http-handler")
				.addSubSee("error-during-request-phase")
				.exception(e)
				.build();
	}

	/**
	 * @return whether the {@link #getLocalPort()} of the handler has to match
	 *         the rule's local port for the rule to apply.
	 */
	public boolean isMatchLocalPort() {
		return true;
	}

	/**
	 * @return the context path of our web application, when running as a servlet with removeContextRoot="true"
	 * (which is the default, when running as a servlet). returns an empty string otherwise (e.g. if not running
	 * as a servlet or when removeContextRoot="false")
	 */
	public String getContextPath(Exchange exc) {
		return "";
	}
}